import assert from "node:assert/strict";
import { mkdtemp, readFile, writeFile, readdir, rm } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { createRequire } from "node:module";
const require=createRequire(import.meta.url);
const { startPersistentTranscriptionJob, getPersistentTranscriptionJob } = require("./test-output/job-store.js");
const dir=await mkdtemp(path.join(os.tmpdir(),"yt-local-durable-"));
process.env.YOUTUBE_TRANSCRIPT_JOB_BACKEND="local";
process.env.YOUTUBE_TRANSCRIPT_JOB_DIR=dir;
process.env.GEMINI_API_KEY="fixture-local-key";
process.env.YOUTUBE_TRANSCRIPT_JOB_SIGNING_KEY="fixture-local-signing-key";
let postCount=0,getCount=0;
let replies=[];
const response=(body)=>({ok:true,headers:new Headers(),json:async()=>body});
global.fetch=async (_url,opts={})=>{
  if(opts.method==="POST")postCount++;
  else getCount++;
  assert.ok(replies.length,"Unexpected provider interaction");
  return response(replies.shift());
};
const args={url:"https://youtu.be/5k0tCrXdIIM",language:"ko-KR",durationSeconds:90,geminiFileUri:"https://generativelanguage.googleapis.com/v1beta/files/localfixture",chunkSeconds:240};
try{
  replies=[{id:"v1_local_durable",status:"in_progress"}];
  const starts=await Promise.all(Array.from({length:8},()=>startPersistentTranscriptionJob(args)));
  assert.equal(postCount,1,"local atomic initial claim must prevent duplicate POST");
  const jobToken=starts[0].jobToken;
  assert.ok(starts.every(x=>x.jobToken===jobToken));
  assert.match(jobToken,/^ytj2\./);
  const stateFiles=(await readdir(dir)).filter(x=>x.endsWith(".json"));
  assert.equal(stateFiles.length,1,"single durable local state file");
  let record=JSON.parse(await readFile(path.join(dir,stateFiles[0]),"utf8"));
  assert.equal(record.phase,"active");
  assert.ok(record.result?.jobToken,"provider interaction saved across restart");
  replies=[{status:"completed",steps:[{type:"model_output",content:[{type:"text",text:"[00:00:00] First sentence\n[00:01:26] Final sentence"}]}]}];
  const done=await getPersistentTranscriptionJob(jobToken);
  assert.equal(done.status,"completed");
  assert.match(done.transcript,/Final sentence/);
  const again=await getPersistentTranscriptionJob(jobToken);
  assert.equal(again.transcript,done.transcript);
  assert.equal(postCount,1);
  assert.equal(getCount,1);
  record=JSON.parse(await readFile(path.join(dir,stateFiles[0]),"utf8"));
  assert.equal(record.phase,"completed");
  assert.equal(record.result?.status,"completed");
  const second={...args,url:"https://youtu.be/G-8cDsHLrD0"};
  replies=[{id:"v1_crash_recover",status:"in_progress"}];
  const pending=await startPersistentTranscriptionJob(second);
  const file2=(await readdir(dir)).filter(x=>x.endsWith(".json")&&x!==stateFiles[0])[0];
  const state2=JSON.parse(await readFile(path.join(dir,file2),"utf8"));
  await writeFile(path.join(dir,file2),JSON.stringify({...state2,phase:"polling",owner:"crashed-worker",updatedAt:Date.now()-21*60_000}));
  const wasPosted=postCount;
  const retry=await getPersistentTranscriptionJob(pending.jobToken);
  assert.equal(retry.status,"in_progress");
  replies=[{status:"completed",steps:[{type:"model_output",content:[{type:"text",text:"[00:00:03] Resumed safely"}]}]}];
  const resumed=await getPersistentTranscriptionJob(pending.jobToken);
  assert.equal(resumed.status,"completed");
  assert.equal(postCount,wasPosted,"safe GET resume must not POST");
  await assert.rejects(getPersistentTranscriptionJob(jobToken.slice(0,-4)+"zzzz"),/signature/);
  console.log(JSON.stringify({status:"PASS",checks:["atomic local claim and no duplicate POST","provider ID persisted in private JSON","completed output across requests","stale GET-only worker recovery","signed token tamper rejection"],postCount,getCount,dirMode:"private"}));
}finally{await rm(dir,{recursive:true,force:true});}
